"""Prepare the full original Instacart same-item benchmark from public CSVs.

The fixed feature matrix is retained for a matched comparator. The adaptive
candidate matrix is generated by prepare_adaptive_instacart.py.
"""
from pathlib import Path
import argparse,gc,hashlib,json,time
import numpy as np
import pandas as pd
from scipy import sparse
from scipy.sparse.linalg import eigsh


def log(s):
    print(time.strftime("%H:%M:%S"), s, flush=True)


def dump(path, obj):
    path.write_text(json.dumps(obj, ensure_ascii=False, indent=2), encoding="utf-8")


def sha256(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as f:
        for b in iter(lambda: f.read(8 * 1024 * 1024), b""):
            h.update(b)
    return h.hexdigest()


def features(df, horizons):
    """Vectorized equivalents of npe_core's causal feature families."""
    df = df.sort_values(["cid", "event_day", "order_number"], kind="stable").reset_index(drop=True)
    cid, starts, sizes = np.unique(df.cid.to_numpy(), return_index=True, return_counts=True)
    rank = np.repeat(np.arange(len(cid)), sizes)
    start = np.repeat(starts, sizes)
    pos = np.arange(len(df)) - start
    days = df.event_day.to_numpy(np.int64)
    gaps = np.zeros(len(df), np.float64)
    gaps[1:] = np.maximum(0, days[1:] - days[:-1])
    gaps[pos == 0] = 0
    # Dataset event_day is integer relative day. Retail timedelta.days is
    # computed separately so sub-day timestamp differences retain the same
    # definition as the thesis instead of differencing normalized dates.
    if "exact_gap" in df:
        gaps = df.exact_gap.to_numpy(np.float64)
    spend = df.sale_price_total.to_numpy(np.float64)
    n = len(df)
    ix = np.arange(n)
    prefix = lambda v: np.r_[0.0, np.cumsum(v, dtype=np.float64)]
    pg, pg2, ps, ps2 = prefix(gaps), prefix(gaps**2), prefix(spend), prefix(spend**2)
    f = {"Days_Since_Last_Purchase": gaps, "Transaction_Count": pos + 1}
    candidates = []
    for lag in [2, 3, 4, 5]:
        a = np.zeros(n)
        valid = pos >= lag - 1
        a[valid] = gaps[ix[valid] - (lag - 1)]
        name = f"Gap{lag}Last"
        f[name] = a
        candidates.append(name)
    for w in [3, 5, 10, 20]:
        left = np.maximum(start, ix - w + 1)
        length = ix - left + 1
        for label, p1, p2 in [("Gap", pg, pg2), ("Spend", ps, ps2)]:
            total, sq = p1[ix + 1] - p1[left], p2[ix + 1] - p2[left]
            mean = total / length
            std = np.sqrt(np.maximum(0, sq - total**2 / length) / np.maximum(1, length - 1))
            std[length == 1] = 0
            f[f"Avg{label}_w{w}"] = mean
            f[f"{label}Std_w{w}"] = std
        candidates += [f"AvgGap_w{w}", f"GapStd_w{w}", f"AvgSpend_w{w}", f"SpendStd_w{w}"]
    cnt = pos + 1
    sumg, sumg2 = pg[ix + 1] - pg[start], pg2[ix + 1] - pg2[start]
    f["AvgGap"] = sumg / cnt
    f["GapStd"] = np.sqrt(np.maximum(0, sumg2 - sumg**2 / cnt) / np.maximum(1, cnt - 1))
    f["GapStd"][cnt == 1] = 0
    f["CumSpend"] = ps[ix + 1] - ps[start]
    f["AvgSpend"] = f["CumSpend"] / cnt
    f["LastAmount"] = spend
    f["RelativeLastAmount"] = np.divide(spend, f["AvgSpend"], out=np.zeros(n), where=f["AvgSpend"] != 0)
    f["CustomerTenure"] = (df.exact_tenure.to_numpy() if "exact_tenure" in df else days - days[start])
    # Offsetting each series makes searchsorted equivalent to searching inside
    # each customer group, including strictly preceding same-day events.
    stride = int(days.max() - days.min() + 100)
    encoded = rank.astype(np.int64) * stride + days - days.min()
    for w in [7, 30]:
        left = np.maximum(start, np.searchsorted(encoded, encoded - w, side="left"))
        f[f"Count_{w}d"] = ix - left
        f[f"Spend_{w}d"] = ps[ix] - ps[left]
        candidates += [f"Count_{w}d", f"Spend_{w}d"]
    dow = df.dow.to_numpy()
    f["sin_dow"], f["cos_dow"] = np.sin(2*np.pi*dow/7), np.cos(2*np.pi*dow/7)
    if "month" in df:
        month = df.month.to_numpy()
        f["sin_month"], f["cos_month"] = np.sin(2*np.pi*month/12), np.cos(2*np.pi*month/12)
    else:
        f["sin_month"], f["cos_month"] = np.zeros(n), np.zeros(n)
    for k in ["line_items", "unique_products_in_event", "quantity"]:
        f[k] = df[k].to_numpy()
    # Last five target intervals are test, preceding five validation for retail.
    # Last interval is test, preceding one validation for Instacart.
    val_origin = sizes - 2*horizons - 1
    train_last_origin = val_origin - horizons
    train_rows = pos <= train_last_origin[rank]
    target = np.zeros(n)
    target[:-1] = gaps[1:]
    last_rows = pos == sizes[rank]-1
    target[last_rows] = np.nan
    train_rows &= ~last_rows
    corr = {}
    yy = target[train_rows]
    for k in candidates:
        xx = f[k][train_rows]
        if np.std(xx) > 1e-9 and np.std(yy) > 1e-9:
            corr[k] = abs(float(np.corrcoef(xx, yy)[0, 1]))
    selected = sorted(corr, key=corr.get, reverse=True)[:5]
    base = ["Days_Since_Last_Purchase", "Transaction_Count", "AvgGap", "GapStd",
            "CumSpend", "AvgSpend", "LastAmount", "RelativeLastAmount",
            "CustomerTenure", "line_items", "unique_products_in_event", "quantity",
            "sin_dow", "cos_dow", "sin_month", "cos_month"]
    names = base + [f"Cluster_{k}" for k in range(4)] + selected
    x = np.column_stack([f[k] if not k.startswith("Cluster_") else np.zeros(n) for k in names]).astype(np.float32)
    # Exact train-only clustering profile used by GTS, before standardization.
    validg = train_rows & (pos > 0)
    ng = np.bincount(rank[validg], minlength=len(cid))
    sg = np.bincount(rank[validg], weights=gaps[validg], minlength=len(cid))
    sg2 = np.bincount(rank[validg], weights=gaps[validg]**2, minlength=len(cid))
    nt = np.bincount(rank[train_rows], minlength=len(cid))
    st = np.bincount(rank[train_rows], weights=spend[train_rows], minlength=len(cid))
    mg = sg / np.maximum(1, ng)
    sd = np.sqrt(np.maximum(0, sg2 - sg**2/np.maximum(1, ng)) / np.maximum(1, ng-1))
    profiles = np.column_stack([np.log1p(mg), np.log1p(sd), np.log1p(nt), np.log1p(np.maximum(0,st/np.maximum(1,nt)))]).astype(np.float32)
    range_gap = np.ones(len(cid), dtype=np.float32)
    min_gap = np.zeros(len(cid), dtype=np.float32)
    for i, (s, m) in enumerate(zip(starts, sizes)):
        available = gaps[s+1:s+int(val_origin[i])+1]
        if len(available):
            range_gap[i] = max(1, float(np.ptp(available)))
            min_gap[i] = float(available.min())
    last_train_day=np.full(len(cid),days.min(),dtype=np.int64)
    np.maximum.at(last_train_day,rank[train_rows],days[train_rows])
    freq=np.bincount(rank[train_rows],weights=df.line_items.to_numpy()[train_rows],minlength=len(cid))
    paper_profiles=np.column_stack([last_train_day.max()-last_train_day,freq]).astype(np.float32)
    return df, x, gaps, cid, starts, sizes, rank, pos, train_rows, profiles, range_gap, {"feature_names":names,"selected_dynamic":selected,"correlations":corr,"_min_gap":min_gap,"_paper_profiles":paper_profiles}


def save_windows(name, df, x, gvec, gaps, cid, starts, sizes, profiles, range_gap, info, horizons):
    out = HERE / "prepared" / name
    out.mkdir(parents=True, exist_ok=True)
    origin, group, split = [], [], []
    for k, (s,m) in enumerate(zip(starts,sizes)):
        m=int(m); s=int(s)
        if horizons == 1:
            # Six-value non-overlapping blocks anchored from validation.
            js = list(range(m-9, 4, -6))[::-1]
            va, te = m-3, m-2
        else:
            js = list(range(10, m-15))
            va, te = m-11, m-6
        for j in js:
            origin.append(s+j);group.append(k);split.append(0)
            assert j+horizons <= va, (name,k,j,va)
        for j,v in [(va,1),(te,2)]:
            assert j>=5
            origin.append(s+j);group.append(k);split.append(v)
    origin, group, split = np.asarray(origin,np.int64),np.asarray(group,np.int32),np.asarray(split,np.int8)
    win = origin[:,None] + np.arange(-4,1)
    assert np.all(df.cid.to_numpy()[win] == cid[group,None])
    num = x[win].astype(np.float32)
    graph = gvec[win].astype(np.float32)
    y = np.column_stack([gaps[origin+h] for h in range(1,horizons+1)]).astype(np.float32)
    if horizons==1:
        # Values at origin include all five previously realized product gaps.
        hist = num[:,:,0]
        ids = df.iloc[origin]
        paper = np.column_stack([ids.user_id,ids.product_id,
                                hist.max(1),hist.min(1),hist.var(1),hist.mean(1),
                                ids.global_last_gap,hist]).astype(np.float32)
    else:
        ten = origin[:,None] + np.arange(-9,1)
        assert np.all(ten>=starts[group,None])
        paper = gaps[ten,:,None] if gaps.ndim>1 else gaps[ten][...,None]
        paper = paper.astype(np.float32)
    original_customer = df.iloc[origin].user_id.to_numpy(np.int32)
    keys = df.iloc[origin][["cid","user_id","order_id","event_day"]].reset_index(drop=True)
    keys.columns=["series_id","customer_id","origin_order_id","origin_day"]
    keys["target_order_id"] = df.order_id.to_numpy()[origin+horizons]
    keys["split"] = split
    keys.to_parquet(out/"keys.parquet",index=False)
    for k,v in {"x_num":num,"x_graph":graph,"y":y,"x_paper":paper,"group":group,
                "customer":original_customer,"split":split,"profiles":profiles,
                "range_gap":range_gap[group],"min_gap":info.pop("_min_gap")[group],
                "paper_profiles":info.pop("_paper_profiles")}.items():
        np.save(out/f"{k}.npy",v)
    info.update(dict(name=name,horizons=horizons,n_series=len(cid),n_events=len(df),
                     n_train=int((split==0).sum()),n_val=int((split==1).sum()),
                     n_test=int((split==2).sum()),n_test_targets=int((split==2).sum()*horizons),
                     x_shape=list(num.shape),paper_shape=list(paper.shape),
                     source_hashes=info.get("source_hashes",{})))
    dump(out/"manifest.json",info)
    log(f"Prepared {name}: {info['n_train']:,} train, {info['n_val']:,} validation, {info['n_test']:,} test series, H={horizons}")


def instacart():
    base=DATA
    orders=pd.read_csv(base/"orders.csv",dtype={"order_id":"int32","user_id":"int32","order_number":"int16","order_dow":"int8","order_hour_of_day":"int8","days_since_prior_order":"float32"})
    orders.sort_values(["user_id","order_number"],inplace=True)
    orders["relative_day"]=orders.days_since_prior_order.fillna(0).groupby(orders.user_id).cumsum().astype(np.int32)
    maxid=int(orders.order_id.max())+1
    lut={}
    for col in ["user_id","order_number","order_dow","relative_day","days_since_prior_order"]:
        a=np.zeros(maxid,dtype=np.float32 if col=="days_since_prior_order" else np.int32)
        a[orders.order_id]=orders[col].fillna(0).to_numpy()
        lut[col]=a
    op=pd.concat([pd.read_csv(base/f,usecols=["order_id","product_id"],dtype={"order_id":"int32","product_id":"int32"})
                  for f in ["order_products__prior.csv","order_products__train.csv"]],ignore_index=True)
    oid=op.order_id.to_numpy(np.int32);pid=op.product_id.to_numpy(np.int32)
    del op;gc.collect()
    pair=lut["user_id"][oid].astype(np.int64)*60000+pid
    uk,counts=np.unique(pair,return_counts=True)
    audit={"n_order_product_rows":len(pair),"pairs_20_purchases":int((counts>=20).sum()),"pairs_21_purchases":int((counts>=21).sum()),"paper_reported_pairs":112796}
    log(f"Instacart history audit: {audit}")
    # Freeze interpretation from the paper's twenty gap entries, not outcomes.
    eligible=uk[counts>=21]
    mask=np.isin(pair,eligible)
    ids=oid[mask]
    basket_n=np.bincount(oid,minlength=maxid).astype(np.float32)
    df=pd.DataFrame({"cid":pair[mask],"user_id":lut["user_id"][ids],"product_id":pid[mask],"order_id":ids,
                     "order_number":lut["order_number"][ids],"event_day":lut["relative_day"][ids],
                     "dow":lut["order_dow"][ids],"global_last_gap":lut["days_since_prior_order"][ids],
                     "sale_price_total":basket_n[ids],"line_items":basket_n[ids],
                     "unique_products_in_event":basket_n[ids],"quantity":basket_n[ids]})
    del pair,uk,counts,mask,ids;gc.collect()
    result=features(df,1)
    df,x,gaps,cid,starts,sizes,rank,pos,tr,profiles,range_gap,info=result
    train_orders=np.zeros(maxid,dtype=bool)
    train_orders[df.order_id.to_numpy()[tr]]=True
    # A basket can occur in several product histories. Remove baskets beyond
    # the earliest validation origin of its actual customer, so another pair
    # cannot silently put a reserved future basket into the fitted graph.
    val_order = df.order_number.to_numpy()[starts+sizes-3]
    cut = pd.Series(val_order,index=df.user_id.to_numpy()[starts]).groupby(level=0).min()
    customer_limit=np.full(int(lut["user_id"].max())+1,0,np.int32)
    customer_limit[cut.index.to_numpy()]=cut.to_numpy()
    train_orders &= lut["order_number"] <= customer_limit[lut["user_id"]]
    # Each original basket contributes once, regardless of how many eligible
    # product histories contain it. Sparse B.T @ B implements co-purchase counts.
    freq=np.bincount(pid[train_orders[oid]])
    top=np.argsort(freq)[::-1][:600]
    top=top[freq[top]>0]
    mapid=np.full(int(pid.max())+1,-1,np.int32);mapid[top]=np.arange(len(top))
    cols=mapid[pid]; use=cols>=0
    b=sparse.coo_matrix((np.ones(int(use.sum()),np.float32),(oid[use],cols[use])),shape=(maxid,len(top))).tocsr()
    b.data[:]=1
    bt=b[train_orders]
    adj=(bt.T@bt).toarray().astype(np.float64)
    np.fill_diagonal(adj,1)
    deg=adj.sum(1); norm=1/np.sqrt(np.maximum(deg,1))
    anorm=adj*norm[:,None]*norm[None,:]
    vals,vecs=eigsh(sparse.csr_matrix(anorm),k=17,which="LA",v0=np.random.default_rng(42).normal(size=len(top)))
    order=np.argsort(vals)[::-1][1:17]
    emb=(vecs[:,order]*np.sqrt(np.maximum(0,vals[order]))).astype(np.float32)
    sums=np.asarray(b@emb,np.float32)
    denom=np.asarray(b.sum(1)).ravel()
    sums/=np.maximum(1,denom)[:,None]
    gvec=sums[df.order_id.to_numpy()]
    del b,bt,sums,oid,pid,cols,use,lut,orders;gc.collect()
    info.update(dict(source="Original Instacart 2017 prior plus train product baskets; complete eligible cohort",
                     history_audit=audit,month_encoding="zero; calendar dates unavailable",amount_proxy="number of products in current order",
                     graph_guard="exclude original-customer baskets after earliest pair validation origin",
                     source_hashes={str(base/f):sha256(base/f) for f in ["orders.csv","order_products__prior.csv","order_products__train.csv"]}))
    save_windows("instacart_pairs",df,x,gvec,gaps,cid,starts,sizes,profiles,range_gap,info,1)

if __name__=='__main__':
    p=argparse.ArgumentParser()
    p.add_argument('--data-root',type=Path,required=True,help='Folder containing orders.csv and both order-product CSVs')
    p.add_argument('--output-root',type=Path,default=Path('work'))
    args=p.parse_args();DATA=args.data_root;HERE=args.output_root
    HERE.mkdir(parents=True,exist_ok=True)
    instacart()
